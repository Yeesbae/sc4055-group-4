def output_distribution(qc, L=HORIZON, n_mem=N_MEM):
    sv = Statevector(qc)
    p4 = sv.probabilities(list(range(n_mem, n_mem + 2 * L))).reshape((4,) * L)
    p4 = np.transpose(p4, list(range(L))[::-1])         # axis t = out_t
    p3 = p4[(slice(0, 3),) * L]
    return p3, float(1 - p3.sum())

def gate_counts(qc, opt=3):
    t = transpile(qc, basis_gates=["cx", "rz", "sx", "x"], optimization_level=opt, seed_transpiler=7)
    ops = t.count_ops()
    return {"cx": int(ops.get("cx", 0)), "depth": int(t.depth())}

# Structured U_s: memory = two 2-qubit slots F (next symbol x), S (symbol after, y)
def slot_angles():
    th_hi = np.zeros((4, 4)); th_lo = np.zeros((4, 4))
    for x in range(3):
        for y in range(3):
            a0, a1, a2 = np.sqrt(E[3 * x + y])
            th_hi[x, y] = 2 * np.arctan2(a2, np.hypot(a0, a1))
            th_lo[x, y] = 2 * np.arctan2(a1, a0)
    return th_hi, th_lo

def structured_step(qc, F, S_, out, th_hi, th_lo):
    for k in range(2):                       # move x from slot F into output
        qc.cx(F[k], out[k]); qc.cx(out[k], F[k])
    ang_hi = [0.0] * 16; ang_lo = [0.0] * 32
    for x in range(4):
        for y in range(4):
            ang_hi[x + 4 * y] = th_hi[x, y]
            ang_lo[x + 4 * y] = th_lo[x, y]  # only when F_hi = 0
    qc.append(UCRYGate(ang_hi), [F[1], out[0], out[1], S_[0], S_[1]])
    qc.append(UCRYGate(ang_lo), [F[0], out[0], out[1], S_[0], S_[1], F[1]])

def slot_memory_state(start):                # index x_F + 4*y_S
    v = np.zeros(16)
    for x in range(3):
        for y in range(3):
            v[x + 4 * y] = SIG[3 * x + y, start]
    return v

def build_A_structured(start, L=HORIZON):
    mem = QuantumRegister(4, "mem")
    outs = [QuantumRegister(2, f"out{t}") for t in range(L)]
    qc = QuantumCircuit(mem, *outs)
    qc.append(StatePreparation(slot_memory_state(start), label="U_ini"), mem[:])
    th_hi, th_lo = slot_angles()
    F, S_ = [mem[0], mem[1]], [mem[2], mem[3]]
    for t in range(L):
        structured_step(qc, F, S_, outs[t], th_hi, th_lo)
        F, S_ = S_, F                        # slots swap roles
    return qc
