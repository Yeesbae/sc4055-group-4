def output_distribution(qc, L=HORIZON, n_mem=N_MEM):
    sv = Statevector(qc)
    p4 = sv.probabilities(list(range(n_mem, n_mem + 2 * L))).reshape((4,) * L)
    p4 = np.transpose(p4, list(range(L))[::-1])         # axis t = out_t
    p3 = p4[(slice(0, 3),) * L]
    return p3, float(1 - p3.sum())

