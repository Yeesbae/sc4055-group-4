def dp(s, L=6, threshold=3, rational=False):
    zero = Fraction(0) if rational else 0.
    a = [[zero for _ in range(threshold + 1)] for _ in range(9)]; a[s][0] = 1
    for _ in range(L):
        b = [[zero for _ in range(threshold + 1)] for _ in range(9)]
